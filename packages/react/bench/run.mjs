import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { build, preview } from 'vite';

const configFile = fileURLToPath(new URL('./vite.config.ts', import.meta.url));
const resultsFile = fileURLToPath(new URL('../../../internal/bench/RESULTS-react.md', import.meta.url));
const SHAPES = ['wide', '10x100k', 'chains64'];
const ALL_SIZES = [10_000, 100_000, 1_000_000];
const PAGE_TIMEOUT_MS = 600_000;
const HAND_WRITTEN_SECTION = '\n## Reference';
const WARM_UP_RUNS = 1;
const MEDIAN_RUNS = 5;

const sizes = process.argv.length > 2 ? process.argv.slice(2).map(Number) : ALL_SIZES;

async function heapUsedMb(cdp) {
  await cdp.send('HeapProfiler.collectGarbage');
  const { metrics } = await cdp.send('Performance.getMetrics');
  return metrics.find((metric) => metric.name === 'JSHeapUsedSize').value / 2 ** 20;
}

async function openBenchPage(browser, url, shape, size) {
  const page = await browser.newPage();
  page.setDefaultTimeout(PAGE_TIMEOUT_MS);
  await page.goto(`${url}?shape=${shape}&size=${size}`);
  await page.waitForFunction(() => 'bench' in window, undefined, { timeout: PAGE_TIMEOUT_MS });
  return page;
}

const median = (values) => [...values].sort((a, b) => a - b)[Math.floor(values.length / 2)];

async function coldFirstRenderMedian(browser, url, shape, size) {
  const runs = [];
  for (let run = 0; run < WARM_UP_RUNS + MEDIAN_RUNS; run++) {
    const page = await openBenchPage(browser, url, shape, size);
    const firstRenderMs = await page.evaluate(() => window.bench.firstRenderMs());
    if (run >= WARM_UP_RUNS) runs.push(firstRenderMs);
    await page.close();
  }
  return median(runs);
}

async function measure(browser, url, shape, size) {
  const firstRenderMs = await coldFirstRenderMedian(browser, url, shape, size);
  const page = await openBenchPage(browser, url, shape, size);
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Performance.enable');
  const setupMs = await page.evaluate(() => window.bench.setupMs);
  const heapBeforeMountMb = await heapUsedMb(cdp);
  await page.evaluate(() => window.bench.mount());
  const heapAfterFirstRenderMb = await heapUsedMb(cdp);
  const interactions = await page.evaluate(() => window.bench.interactions());
  await page.close();
  return { shape, size, setupMs, firstRenderMs, heapBeforeMountMb, heapAfterFirstRenderMb, ...interactions };
}

const ms = (value) => `${value.toFixed(1)} ms`;
const mb = (value) => `${value.toFixed(1)} MB`;
const percent = (share) => `${(share * 100).toFixed(1)}%`;
const frames = (stats) =>
  `${ms(stats.longestFrameMs)} / ${percent(stats.shareOfFramesOver25Ms)} / ${stats.longAnimationFrames} / ${stats.longTasks}`;
const FRAME_COLUMNS = 'longest frame / frames > 25 ms / long animation frames / long tasks';

function resultsTable(results) {
  const header = [
    'shape',
    'files',
    'adapter setup',
    'first render (cold page)',
    'heap: workspace / page',
    'expand, fetching (fetchDepth 1)',
    'expand, loaded',
    'collapse',
    'viewports scrolled',
    `scroll: ${FRAME_COLUMNS}`,
    'rename: optimistic',
    `rename round trip: ${FRAME_COLUMNS}`,
    'drag to root: optimistic',
    'search: first result',
    `5k event burst under the top folder: ${FRAME_COLUMNS}`,
  ];
  const rows = results.map((result) => [
    result.shape,
    result.size.toLocaleString('en-US'),
    ms(result.setupMs),
    ms(result.firstRenderMs),
    `${mb(result.heapAfterFirstRenderMb - result.heapBeforeMountMb)} / ${mb(result.heapAfterFirstRenderMb)}`,
    ms(result.expandThatFetchesMs),
    ms(result.expandMs),
    ms(result.collapseMs),
    result.viewportsScrolled,
    frames(result.scroll),
    ms(result.renameMs),
    frames(result.renameRoundTrip),
    ms(result.dragMs),
    ms(result.searchMs),
    frames(result.burst),
  ]);
  return [header, header.map(() => '---'), ...rows].map((cells) => `| ${cells.join(' | ')} |`).join('\n');
}

function handWrittenSectionOf(file) {
  if (!existsSync(file)) return '';
  const previous = readFileSync(file, 'utf8');
  const start = previous.indexOf(HAND_WRITTEN_SECTION);
  return start < 0 ? '' : previous.slice(start);
}

function writeResults(results, browserVersion) {
  const report = [
    '# @workspacekit/react benchmark results',
    '',
    `Generated by \`pnpm --filter @workspacekit/react bench\` on ${new Date().toISOString().slice(0, 10)}.`,
    `Chromium ${browserVersion}, headless, production React with the React Compiler. Each figure is the median of 5 runs after 1 warm-up run;`,
    'each first render is the first mount in a freshly loaded page.',
    'The page renders `<Workspace adapter={createMemoryAdapter({ files: generateShape(shape, files) })} />` at 900 x 600.',
    'Heap comes from CDP (`HeapProfiler.collectGarbage`, then `Performance.getMetrics` JSHeapUsedSize): "workspace" is',
    'the growth from mounting the workspace, "page" also counts the in-page memory adapter and its generated files.',
    'Frame columns come from requestAnimationFrame timestamps, plus the long-animation-frame and longtask entries.',
    'The top folder is `wide` (all files), `d0` (a tenth of them) or `c0` (one 64-deep chain); the burst lands under it.',
    'Interactions run on a mounted workspace whose adapter answers moves after 50 ms, as a server would: "optimistic"',
    'is the time to the change on screen before that answer; "round trip" covers the answer and the reload after it.',
    '',
    resultsTable(results),
    '',
  ].join('\n');
  mkdirSync(dirname(resultsFile), { recursive: true });
  writeFileSync(resultsFile, report + handWrittenSectionOf(resultsFile));
}

await build({ configFile });
const server = await preview({ configFile, preview: { port: 0, strictPort: false } });
const browser = await chromium.launch({ args: ['--js-flags=--expose-gc'] });
try {
  const results = [];
  for (const size of sizes) {
    for (const shape of SHAPES) {
      process.stdout.write(`${shape} ${size}... `);
      results.push(await measure(browser, server.resolvedUrls.local[0], shape, size));
      process.stdout.write('done\n');
    }
  }
  writeResults(results, browser.version());
  process.stdout.write(`wrote ${resultsFile}\n`);
} finally {
  await browser.close();
  await server.close();
}
