import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const NOTICES = new URL('../THIRD_PARTY_NOTICES.md', import.meta.url);
const COPYLEFT_OR_PROPRIETARY = /\b(?:A|L)?GPL|General Public License|\bUNLICENSED\b/i;
const REPORT_BUFFER_BYTES = 64 * 1024 * 1024;
const UNREADABLE = /^(?:unknown|see licen[cs]e in\b)/i;

/**
 * Dependencies whose licence field the check would reject but which were checked by hand, keyed by name.
 * `license` is the exact licence string pnpm reported when they were checked, so a changed licence fails
 * the check again; `take` is the licence they are used under, as the notices state it.
 *
 * @example
 * ALLOW_LIST.jszip.take; // 'MIT'
 */
export const ALLOW_LIST = Object.freeze({
  'mtx-decompressor': {
    license: 'MPL-2.0',
    take: 'MPL-2.0',
    reason: 'weak copyleft, bundled unmodified inside pptx-renderer; its source stays available upstream',
  },
  jszip: {
    license: '(MIT OR GPL-3.0-or-later)',
    take: 'MIT',
    reason: 'dual-licensed; used under MIT',
  },
  dompurify: {
    license: '(MPL-2.0 OR Apache-2.0)',
    take: 'Apache-2.0',
    reason: 'dual-licensed; used under Apache-2.0',
  },
});

const byCodePoint = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * Flattens the output of `pnpm licenses list --prod --json -r` into one entry per installed version,
 * sorted by name, then version, by code point so the order is the same in every locale.
 *
 * @example
 * dependenciesOf({ MIT: [{ name: 'react', versions: ['19.3.1'], license: 'MIT' }] });
 * // [{ name: 'react', version: '19.3.1', license: 'MIT', homepage: '' }]
 */
export function dependenciesOf(report) {
  return Object.values(report)
    .flat()
    .flatMap(({ name, versions, license, homepage }) =>
      versions.map((version) => ({ name, version, license: license ?? 'Unknown', homepage: homepage ?? '' })),
    )
    .sort((a, b) => byCodePoint(a.name, b.name) || byCodePoint(a.version, b.version));
}

/**
 * The dependencies that are GPL, AGPL, LGPL (in any spelling, such as `GPLv3` or "GNU General Public
 * License") or UNLICENSED, or whose licence cannot be read, and are not on `allowList`; plus every
 * allow-listed dependency whose reported licence is no longer the string that was checked by hand.
 *
 * @example
 * licenseViolations([{ name: 'hyperformula', version: '3.5.0', license: 'GPL-3.0-only', homepage: '' }]);
 * // [{ name: 'hyperformula', … }]
 */
export function licenseViolations(dependencies, allowList = ALLOW_LIST) {
  return dependencies.filter(({ name, license }) =>
    Object.hasOwn(allowList, name)
      ? allowList[name].license !== license
      : COPYLEFT_OR_PROPRIETARY.test(license) || UNREADABLE.test(license),
  );
}

const usedUnder = ({ name, license }) => ALLOW_LIST[name]?.take ?? license;

/**
 * The THIRD_PARTY_NOTICES.md text: a table of every production dependency with the licence it is used
 * under, followed by the reason for each allow-listed one.
 *
 * @example
 * writeFileSync('THIRD_PARTY_NOTICES.md', noticesMarkdown(dependenciesOf(report)));
 */
export function noticesMarkdown(dependencies) {
  const rows = dependencies.map(
    (dependency) =>
      `| ${dependency.name} | ${dependency.version} | ${usedUnder(dependency)} | ${dependency.homepage} |`,
  );
  const present = new Set(dependencies.map(({ name }) => name));
  const notes = Object.entries(ALLOW_LIST)
    .filter(([name]) => present.has(name))
    .map(([name, { license, take, reason }]) => `- ${name} (${license}): used under ${take}; ${reason}.`);
  return [
    '# Third-party notices',
    '',
    'The production dependencies of the workspace packages and the licences they are used under. The list is',
    "pnpm's production tree, so it also names peers that pnpm installs beside a dependency, optional ones included",
    '(such as `typescript` for the Lexical packages), whether or not our code imports them.',
    'Generated by `node scripts/check-licenses.mjs --write`; do not edit by hand.',
    '',
    '| Package | Version | Licence | Homepage |',
    '| --- | --- | --- | --- |',
    ...rows,
    ...(notes.length > 0 ? ['', '## Hand-checked licences', '', ...notes] : []),
    '',
  ].join('\n');
}

function readReport(args) {
  const reportFlag = args.indexOf('--report');
  if (reportFlag !== -1) return JSON.parse(readFileSync(args[reportFlag + 1], 'utf8'));
  const report = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json', '-r'], {
    encoding: 'utf8',
    maxBuffer: REPORT_BUFFER_BYTES,
  });
  return JSON.parse(report);
}

function violationMessage({ name, version, license }) {
  const allowed = ALLOW_LIST[name];
  if (allowed) {
    return (
      `${name}@${version}: licence is now "${license}", but "${allowed.license}" was checked by hand. ` +
      'Check the new licence and update its ALLOW_LIST entry in scripts/check-licenses.mjs.'
    );
  }
  return (
    `${name}@${version}: ${license}. Replace it with a permissively licensed package, or check its licence ` +
    'by hand and add it to ALLOW_LIST in scripts/check-licenses.mjs with the reported licence and the reason.'
  );
}

function main(args) {
  const dependencies = dependenciesOf(readReport(args));
  const violations = licenseViolations(dependencies);
  for (const violation of violations) console.error(violationMessage(violation));
  if (violations.length > 0) return 1;
  const notices = noticesMarkdown(dependencies);
  if (args.includes('--write')) {
    writeFileSync(NOTICES, notices);
    return 0;
  }
  if (!existsSync(NOTICES) || readFileSync(NOTICES, 'utf8') !== notices) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run `node scripts/check-licenses.mjs --write`.');
    return 1;
  }
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === realpathSync(process.argv[1])) {
  process.exitCode = main(process.argv.slice(2));
}
